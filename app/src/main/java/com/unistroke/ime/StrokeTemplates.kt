package com.unistroke.ime

/**
 * 一筆書きテンプレート。
 * [points] は正規化座標 (0..1, y は下向き) のポリラインで、点の順序がストローク方向を表す。
 */
data class StrokeTemplate(val symbol: String, val points: List<Pt>)

/** 入力ゾーン。左 2/3 が英字、右 1/3 が数字。 */
enum class Zone { ALPHA, NUMBER }

/**
 * 記号シフトの状態。どのテンプレートセットで認識するかを決める。
 * PUNCTUATION / EXTENDED は 1 ストロークで自動的に NORMAL へ戻る。
 */
enum class SymbolMode { NORMAL, PUNCTUATION, EXTENDED }

