    private fun t(symbol: String, vararg xy: Float): StrokeTemplate {
        require(xy.size >= 4 && xy.size % 2 == 0) { "invalid template: $symbol" }
        val points = ArrayList<Pt>(xy.size / 2)
        var i = 0
        while (i < xy.size) {
            points += Pt(xy[i], xy[i + 1])
            i += 2
        }
        return StrokeTemplate(symbol, points)
    }

