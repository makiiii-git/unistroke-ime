/**
 * 内蔵フレーズ辞書。読み -> 表記。
 *
 * 履歴がまだ空の初回から予測が効くようにするための最低限のセット。
 * 挨拶・定型句・ビジネス表現・日付/曜日・機能語・IT 用語を中心に約 350 件。
 *
 * 1 行 "よみ=표記" 形式の生文字列で持ち、初回アクセス時にだけパースする。
 */
object PhraseDictionary {

    /** 読みの昇順に並べた (読み, 表記) のリスト。 */
    val entries: List<Pair<String, String>> by lazy {
        RAW.lineSequence()
            .map { it.trim() }
            .filter { it.isNotEmpty() && !it.startsWith("#") }
            .mapNotNull { line ->
                val i = line.indexOf('=')
                if (i <= 0 || i == line.length - 1) null
                else line.substring(0, i) to line.substring(i + 1)
            }
            .distinctBy { it.first + "\u0000" + it.second }
            .sortedBy { it.first }
            .toList()
    }

    /** [prefix] で前方一致する項目を、読みの短い順に返す。 */
    fun startingWith(prefix: String, limit: Int): List<Pair<String, String>> {
        if (prefix.isEmpty()) return emptyList()
        val out = ArrayList<Pair<String, String>>()
        for (e in entries) {
            if (e.first.startsWith(prefix)) {
                out.add(e)
                if (out.size >= limit * 3) break
            }
        }
        // 読みが短い = 補完量が少ない候補を優先。同長なら元順。
        return out.sortedBy { it.first.length }.take(limit)
    }

